function where(t) {
  if (!t.where) return '';
  return `
    <div class="help-where">
      <span class="help-where-head">ひらきかた</span>
      <span class="help-path">${t.where.map((w) => `<span>${esc(w)}</span>`).join('<span class="help-arrow" aria-hidden="true">→</span>')}</span>
    </div>`;
}

function openButtons(t) {
  if (!t.open) return '';
  return `<div class="help-open">${t.open.map(([route, label, ...params]) =>
    `<a class="btn btn-small btn-primary" href="${href(route, ...params)}">${esc(label ?? `${ROUTES[route].title}をひらく`)}</a>`).join('')}</div>`;
}

function item(t, openId) {
  return `
    <details class="help-item" id="help-${t.id}" ${t.id === openId ? 'open' : ''}>
      <summary>
        <span class="help-icon" aria-hidden="true">${t.icon}</span>
        <span class="help-head"><span class="help-title">${esc(t.title)}</span><span class="help-what">${t.what}</span></span>
        <span class="help-chev" aria-hidden="true">›</span>
      </summary>
      <div class="help-body">
        ${where(t)}
        ${t.steps ? `<ul class="help-steps">${t.steps.map((s) => `<li>${s}</li>`).join('')}</ul>` : ''}
        ${t.body ?? ''}
        ${openButtons(t)}
      </div>
    </details>`;
}

export function renderHelp(el, [openId]) {
  el.innerHTML = `
    <p class="hint hint-top">知りたいところをタップすると、くわしい説明が開きます。もう一度タップすると閉じます。</p>
    <section class="group">
      <h2 class="section-title">機能ごとの使い方</h2>
      <div class="help-list">${FEATURES.map((t) => item(t, openId)).join('')}</div>
    </section>
    <section class="group">
      <h2 class="section-title">忘れやすい操作</h2>
      <div class="help-list">${HOWTOS.map((t) => item(t, openId)).join('')}</div>
    </section>
  `;
  // 画面を開いたあとに上までスクロールされるので、そのあとで項目まで動かす
  if (openId) requestAnimationFrame(() => el.querySelector(`#help-${CSS.escape(openId)}`)?.scrollIntoView({ block: 'start' }));
}
